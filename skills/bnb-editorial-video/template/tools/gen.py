#!/usr/bin/env python3
"""Regenerate every derived file of a BNB editorial HyperFrames project from its config.

Run from the project root after ANY change to project.json, lines.json or timing.json:
    python3 tools/gen.py

Reads   project.json   format (9:16 | 16:9), series, title, brand, theme, fonts, scenes[]
        timing.json    word timings from scripts/make_vo.py (if missing: an ESTIMATE from lines.json is
                       used so you can scaffold and snapshot before the voice exists; rerun after make_vo)
        lines.json     the locked script [{id, text}]
Writes  assets/project.js        window.PROJECT (format, canvas, scenes with start/dur, theme) -> BNB.SCENES
        assets/timing.js         window.TIMING (lines + words, .at(), .line(), .rng())
        assets/theme.css         colour overrides from project.json "theme"
        index.html               root composition: bg, one host per scene, chrome, captions, audio
        compositions/captions.html  sentence-level editorial subtitles (DESIGN.md §7)
        compositions/<id>.html   ONLY if missing: from _scene-template.html (or _endcard-template.html)
and patches data-duration in every composition so slots, hosts and files always agree.
Never hand-edit the generated files; edit this generator or the config.
"""
import json, os, re, sys, html

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

P = json.load(open("project.json"))
FMT = "16:9" if P.get("format") == "16:9" else "9:16"
W, H = (1920, 1080) if FMT == "16:9" else (1080, 1920)
FPS = int(P.get("fps", 30))
LINES = json.load(open("lines.json")) if os.path.exists("lines.json") else []

# ---------------------------------------------------------------- timing
if os.path.exists("timing.json"):
    T = json.load(open("timing.json"))
    estimated = False
else:
    # Estimate (2.6 words/s, 0.4 s lead, 0.4 s gaps, 1.4 s tail) so the project can be scaffolded and checked
    # before the voice exists. Replace by running scripts/make_vo.py.
    t, out = 0.4, []
    for i, L in enumerate(LINES):
        if i: t += float(L.get("gap", 0.4))
        words = L["text"].split(); dur = max(0.8, len(words) / 2.6)
        wt = [len(re.sub(r"\W", "", w)) + 1.5 for w in words]; tot = sum(wt); c = t; ws = []
        for w, k in zip(words, wt):
            d = dur * k / tot; ws.append({"w": w, "s": round(c, 3), "e": round(c + d, 3)}); c += d
        out.append({"id": L["id"], "text": L["text"], "start": round(t, 3), "end": round(t + dur, 3), "words": ws}); t += dur
    T = {"total": round(t + 1.4, 2), "fps": FPS, "w": W, "h": H, "lines": out}
    estimated = True
TOTAL = float(T["total"])
LBY = {l["id"]: l for l in T["lines"]}

# ---------------------------------------------------------------- scenes
scenes = []
for i, s in enumerate(P["scenes"]):
    lines = s.get("lines") or []
    for lid in lines:
        if lid not in LBY: sys.exit("gen.py: scene %s uses line %s, which is not in timing.json" % (s["id"], lid))
    start = 0.0 if i == 0 else (LBY[lines[0]]["start"] if lines else None)
    if start is None: sys.exit("gen.py: scene %s needs at least one line" % s["id"])
    scenes.append(dict(s, n=i + 1, start=round(start, 3), lines=lines, line=lines[0] if lines else ""))
for i, s in enumerate(scenes):
    end = scenes[i + 1]["start"] if i + 1 < len(scenes) else TOTAL
    s["dur"] = round(end - s["start"], 3)
    if s["dur"] <= 0.3: sys.exit("gen.py: scene %s has no time (%.3f s): check its lines" % (s["id"], s["dur"]))
covered = [l for s in scenes for l in s["lines"]]
missing = [l["id"] for l in T["lines"] if l["id"] not in covered]
if missing: print("gen.py WARNING: lines not assigned to any scene:", ", ".join(missing))

# ---------------------------------------------------------------- theme + fonts
PALETTE = {
    "ink": "#06162a", "ground": "#0b2139", "ground2": "#10294a", "navy": "#0e2a47",
    "chalk": "#eef3fa", "chalk2": "rgba(238,243,250,0.74)", "chalk3": "rgba(238,243,250,0.44)", "chalk4": "rgba(238,243,250,0.16)",
    "blue": "#8fb3da", "capMuted": "#7d93ae", "concrete": "#627387", "concreteDry": "#a7b3c1", "aggregate": "#3e4d60",
    "brick": "#a0624e", "point": "#ff8a3d", "water": "#4fc3f7", "green": "#7ce0a3", "red": "#ff5a5a", "heat": "#f2c08a",
}
THEME = P.get("theme") or {}
unknown = [k for k in THEME if k not in PALETTE and not k.startswith("--")]
if unknown: print("gen.py WARNING: unknown theme keys (ignored by BNB.C):", ", ".join(unknown))
PAL = dict(PALETTE, **{k: v for k, v in THEME.items() if not k.startswith("--")})
def cssvar(k): return "--" + re.sub(r"(\d+)", r"-\1", re.sub(r"([A-Z])", lambda m: "-" + m.group(1).lower(), k))
with open("assets/theme.css", "w") as f:
    f.write("/* GENERATED by tools/gen.py from project.json \"theme\". Edit the config, not this file. */\n:root {\n")
    for k, v in THEME.items():
        f.write("  %s: %s;\n" % (k if k.startswith("--") else cssvar(k), v))
    f.write("}\n")

FONTS = P.get("fonts") or [
    {"family": "Fraunces", "file": "assets/fonts/Fraunces-var.woff2", "weight": "100 900", "style": "normal"},
    {"family": "Fraunces", "file": "assets/fonts/Fraunces-var-italic.woff2", "weight": "100 900", "style": "italic"},
    {"family": "InterVar", "file": "assets/fonts/Inter-var.woff2", "weight": "100 900", "style": "normal"},
    {"family": "Plex Mono", "file": "assets/fonts/IBMPlexMono-400.woff2", "weight": "400", "style": "normal"},
    {"family": "Plex Mono", "file": "assets/fonts/IBMPlexMono-500.woff2", "weight": "500", "style": "normal"},
    {"family": "Plex Mono", "file": "assets/fonts/IBMPlexMono-600.woff2", "weight": "600", "style": "normal"},
]
font_css = "\n".join('      @font-face { font-family: "%s"; src: url("%s") format("woff2"); font-weight: %s; font-style: %s; font-display: block; }'
                     % (f["family"], f["file"], f["weight"], f.get("style", "normal")) for f in FONTS)

# ---------------------------------------------------------------- assets/project.js + timing.js
PJ = {"slug": P.get("slug"), "format": FMT, "W": W, "H": H, "fps": FPS, "series": P.get("series", ""), "title": P.get("title", ""),
      "brand": P.get("brand", {}), "total": TOTAL, "theme": {k: v for k, v in THEME.items() if not k.startswith("--")},
      "scenes": [{"id": s["id"], "n": s["n"], "start": s["start"], "dur": s["dur"], "lines": s["lines"], "line": s["line"],
                  "kicker": "%02d — %s" % (s["n"], s.get("kicker", ""))} for s in scenes]}
with open("assets/project.js", "w") as f:
    f.write("/* GENERATED by tools/gen.py from project.json + timing.json. Do not edit by hand. */\n")
    f.write("window.PROJECT = %s;\n" % json.dumps(PJ, indent=1, ensure_ascii=False))

tl_lines = [{"id": l["id"], "start": l["start"], "end": l["end"], "words": [[w["w"], round(w["s"], 3), round(w["e"], 3)] for w in l["words"]]} for l in T["lines"]]
with open("assets/timing.js", "w") as f:
    f.write("/* GENERATED by tools/gen.py from timing.json%s. Do not edit by hand. */\n" % (" (ESTIMATED: no timing.json yet)" if estimated else ""))
    f.write("window.TIMING = { total: %s, estimated: %s, lines: %s };\n" % (TOTAL, "true" if estimated else "false", json.dumps(tl_lines, ensure_ascii=False)))
    f.write("""window.TIMING.line = function (lineId) {
  var l = window.TIMING.lines.filter(function (x) { return x.id === lineId; })[0];
  if (!l) throw new Error("TIMING.line: no line " + lineId);
  return l;
};
window.TIMING.at = function (lineId, word, n) {
  n = n || 1;
  var key = String(word).toLowerCase().replace(/[^a-z0-9']/g, "");
  var line = window.TIMING.line(lineId), seen = 0;
  for (var i = 0; i < line.words.length; i++) {
    if (line.words[i][0].toLowerCase().replace(/[^a-z0-9']/g, "") === key && ++seen === n) return line.words[i][1];
  }
  throw new Error("TIMING.at: no word " + word + " (#" + n + ") in " + lineId);
};
window.TIMING.rng = function (seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    var t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};
""")

# ---------------------------------------------------------------- scene files (create if missing) + durations
os.makedirs("compositions", exist_ok=True)
signoff = (P.get("brand") or {}).get("signoff") or "%s · %s" % ((P.get("brand") or {}).get("name", "BuyNBuild"), P.get("series", ""))
for i, s in enumerate(scenes):
    path = "compositions/%s.html" % s["id"]
    if os.path.exists(path): continue
    endcard = s.get("type") == "endcard"
    src = open("compositions/_endcard-template.html" if endcard else "compositions/_scene-template.html").read()
    last = i == len(scenes) - 1
    vo = " ".join(LBY[l]["text"] for l in s["lines"]).replace("--", "-")
    rep = {
        "__ID__": s["id"], "__NN__": "%02d" % s["n"], "__N__": str(s["n"]), "__KICKER__": html.escape(s.get("kicker", "")),
        "__LINES__": "+".join(s["lines"]), "__LINE__": s["line"], "__VO__": html.escape(vo), "__DUR__": "%g" % s["dur"],
        "__HEADLINE__": s.get("headline") or html.escape(s.get("kicker", "Headline")),
        "__DECK__": s.get("deck", ""), "__FIGCAP__": html.escape(s.get("figcap", "Figure")),
        "__SIGNOFF__": html.escape(signoff), "__TAG__": html.escape(s.get("tag") or P.get("title", "")),
        "__EXIT__": ("// last scene: no exit, the film ends on this frame" if last else
                     'B.a.exit(tl, "#%s-cam", SC.dur - 0.22, 0.2);' % s["id"]),
    }
    for k in sorted(rep, key=len, reverse=True): src = src.replace(k, rep[k])
    if not s.get("deck") and not endcard:
        src = re.sub(r'\n\s*<p class="bnb-deck" id="%s-deck"></p>' % s["id"], "", src)
    open(path, "w").write(src)
    print("created", path, "(endcard)" if endcard else "")

def patch_duration(path, cid, dur):
    if not os.path.exists(path): return
    s = open(path).read()
    s2 = re.sub(r'(data-composition-id="%s"\s+data-duration=")[^"]*(")' % re.escape(cid), r"\g<1>%g\g<2>" % dur, s)
    if s2 != s: open(path, "w").write(s2)
for s in scenes: patch_duration("compositions/%s.html" % s["id"], s["id"], s["dur"])
for cid in ("bg", "chrome"): patch_duration("compositions/%s.html" % cid, cid, TOTAL)
# series rail text
cp = "compositions/chrome.html"
if os.path.exists(cp):
    c = open(cp).read()
    c = re.sub(r'(<span id="chrome-series"[^>]*>)[^<]*(</span>)', lambda m: m.group(1) + html.escape(P.get("series", "")) + m.group(2), c)
    c = re.sub(r'(<span id="chrome-title"[^>]*>)[^<]*(</span>)', lambda m: m.group(1) + html.escape(P.get("title", "")) + m.group(2), c)
    open(cp, "w").write(c)

# ---------------------------------------------------------------- captions (DESIGN.md §7)
MAXW = int(P.get("captionMaxWords", 13))
words = [{"t": w["w"], "s": w["s"], "e": w["e"], "line": l["id"]} for l in T["lines"] for w in l["words"]]
groups, cur = [], []
for i, w in enumerate(words):
    cur.append(w); nxt = words[i + 1] if i + 1 < len(words) else None
    if re.search(r"[.?!]$", w["t"]) or (w["t"].endswith(",") and len(cur) >= 4) or len(cur) >= MAXW or nxt is None or nxt["line"] != w["line"]:
        groups.append(cur); cur = []
cap = []
for gi, g in enumerate(groups):
    start = max(0.12, g[0]["s"] - 0.08); end = g[-1]["e"] + 0.6
    if gi + 1 < len(groups): end = min(end, groups[gi + 1][0]["s"] - 0.08)
    cap.append((start, min(end, TOTAL), g))
cap_html = "\n".join(
    '        <div id="cap-%d" class="cap clip" data-start="%.3f" data-duration="%.3f" data-track-index="0"><p class="cap-line" id="cap-%d-line">%s</p></div>'
    % (gi, s_, e_ - s_, gi, " ".join('<span class="cw" id="cap-%d-%d">%s</span>' % (gi, wi, html.escape(w["t"])) for wi, w in enumerate(g)))
    for gi, (s_, e_, g) in enumerate(cap))
cap_js = ",".join("[%.3f,%.3f,[%s]]" % (s_, e_, ",".join("%.3f" % w["s"] for w in g)) for s_, e_, g in cap)
open("compositions/captions.html", "w").write("""<!doctype html>
<html lang="en">
  <body>
    <template>
      <!-- GENERATED by tools/gen.py — edit the generator, not this file. Style: DESIGN.md §7 -->
      <div id="root" data-composition-id="captions" data-duration="%(total)g">
        <style>
          #root { position: absolute; inset: 0; pointer-events: none; }
          .cap { position: absolute; left: 0; top: var(--cap-top); width: var(--W); height: 150px; overflow: visible; }
          .cap-line {
            margin: 0 auto; width: var(--cap-w); text-align: center;
            font-family: var(--f-sans); font-weight: 500; font-size: var(--cap-size); line-height: var(--cap-lh);
            letter-spacing: -0.012em; color: %(muted)s; text-wrap: balance;
            text-shadow: 0 2px 18px rgba(6, 22, 42, 0.9);
          }
          .cw { display: inline-block; position: relative; }
        </style>
%(groups)s
        <script>
          (function () {
            // [groupStart, groupEnd, [wordStart...]] in film seconds
            var G = [%(js)s];
            var tl = gsap.timeline({ paused: true });
            G.forEach(function (g, gi) {
              var line = "#cap-" + gi + "-line";
              tl.fromTo(line, { opacity: 0, filter: "blur(5px)" }, { opacity: 1, filter: "blur(0px)", duration: 0.22, ease: "power3.out" }, g[0]);
              tl.to(line, { opacity: 0, filter: "blur(4px)", duration: 0.12, ease: "power2.in" }, g[1] - 0.12);
              g[2].forEach(function (ws, wi) {
                // spoken words settle to chalk; unspoken stay muted
                tl.fromTo("#cap-" + gi + "-" + wi, { color: "%(muted)s" }, { color: "%(chalk)s", duration: 0.14, ease: "power2.out" }, ws);
              });
            });
            window.__timelines["captions"] = tl;
          })();
        </script>
      </div>
    </template>
  </body>
</html>
""" % {"total": TOTAL, "groups": cap_html, "js": cap_js, "muted": PAL["capMuted"], "chalk": PAL["chalk"]})

# ---------------------------------------------------------------- index.html
audio = None
for cand in [P.get("audio"), "assets/audio/final_mix.wav", "assets/audio/narration.wav"]:
    if cand and os.path.exists(cand): audio = cand; break
def host(cid, src, start, dur, track, kind, z):
    return ('      <div id="%s" data-composition-id="%s" data-composition-src="%s"\n        data-start="%g" data-duration="%g" data-track-index="%d" data-track-kind="%s"\n'
            '        data-width="%d" data-height="%d" style="z-index: %d"></div>' % (cid, cid, src, start, dur, track, kind, W, H, z))
scene_hosts = "\n".join(host(s["id"], "compositions/%s.html" % s["id"], s["start"], s["dur"], 1, "graphics", 10) for s in scenes)
audio_tag = ('      <audio id="mix" class="clip" src="%s" data-start="0" data-duration="%g"\n        data-track-index="4" data-volume="1"></audio>' % (audio, TOTAL)) if audio else "      <!-- no audio yet: run scripts/make_vo.py (+ make_audio.py), then tools/gen.py -->"
vars_json = json.dumps([{"id": "series", "type": "string", "label": "Series tag", "default": P.get("series", "")},
                        {"id": "title", "type": "string", "label": "Episode title", "default": P.get("title", "")}], ensure_ascii=False)
open("index.html", "w").write("""<!doctype html>
<!-- GENERATED by tools/gen.py from project.json. Edit the config and rerun, not this file. -->
<html lang="en" data-format="%(fmtattr)s"
  data-composition-variables='%(vars)s'>
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=%(W)d, height=%(H)d" />
    <!-- GSAP vendored locally (no CDN at render time). -->
    <script src="assets/vendor/gsap.min.js"></script>
    <script src="assets/project.js"></script>
    <script src="assets/timing.js"></script>
    <link rel="stylesheet" href="assets/bnb.css" />
    <link rel="stylesheet" href="assets/theme.css" />
    <script src="assets/bnb.js"></script>
    <style>
%(fonts)s
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { margin: 0; width: %(W)dpx; height: %(H)dpx; overflow: hidden; background: %(ground)s; }
      #root { position: relative; width: %(W)dpx; height: %(H)dpx; overflow: hidden; font-family: var(--f-sans); color: var(--chalk); }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="%(total)g" data-fps="%(fps)d" data-width="%(W)d" data-height="%(H)d">
      <!-- Ground: page, blueprint grid, vignette, slow drift -->
%(bg)s

      <!-- Scenes, back to back on one lane. Each scene file owns its entrance and exit. -->
%(scenes)s

      <!-- Series rail + chapter progress + grain, whole film -->
%(chrome)s

      <!-- Editorial subtitles, generated from timing.json -->
%(captions)s

%(audio)s
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
""" % {"fmtattr": "16x9" if FMT == "16:9" else "9x16", "vars": vars_json, "W": W, "H": H, "fonts": font_css, "ground": PAL["ground"],
       "total": TOTAL, "fps": FPS, "bg": host("bg", "compositions/bg.html", 0, TOTAL, 0, "graphics", 1), "scenes": scene_hosts,
       "chrome": host("chrome", "compositions/chrome.html", 0, TOTAL, 2, "graphics", 40),
       "captions": host("captions", "compositions/captions.html", 0, TOTAL, 3, "captions", 50), "audio": audio_tag})

# ---------------------------------------------------------------- summary
print("format %s  %dx%d  total %.2f s%s  audio: %s" % (FMT, W, H, TOTAL, "  (ESTIMATED timing)" if estimated else "", audio or "none"))
for s in scenes:
    print("  %-4s %6.3f +%6.3f  %-28s %s" % (s["id"], s["start"], s["dur"], "%02d — %s" % (s["n"], s.get("kicker", "")), "+".join(s["lines"])))
print("captions: %d groups" % len(cap))
