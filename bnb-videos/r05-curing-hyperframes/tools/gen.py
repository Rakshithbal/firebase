#!/usr/bin/env python3
"""Generate assets/timing.js and compositions/captions.html from the source timing.json.
Run from the project root: python3 tools/gen.py"""
import json, re, os
SRC = "/home/user/firebase/bnb-videos/r05-curing/timing.json"
d = json.load(open(SRC))
os.makedirs("assets", exist_ok=True)
lines = [{"id": l["id"], "start": l["start"], "end": l["end"],
          "words": [[w["w"], round(w["s"], 3), round(w["e"], 3)] for w in l["words"]]} for l in d["lines"]]
with open("assets/timing.js", "w") as f:
    f.write("/* Generated by tools/gen.py from r05-curing/timing.json. Do not edit by hand. */\n")
    f.write("window.R05 = { total: %s, lines: %s };\n" % (d["total"], json.dumps(lines)))
    f.write("""window.R05.at = function (lineId, word, n) {
  n = n || 1;
  var key = String(word).toLowerCase().replace(/[^a-z']/g, "");
  var line = window.R05.lines.filter(function (l) { return l.id === lineId; })[0];
  var seen = 0;
  for (var i = 0; i < line.words.length; i++) {
    if (line.words[i][0].toLowerCase().replace(/[^a-z']/g, "") === key && ++seen === n) return line.words[i][1];
  }
  throw new Error("R05.at: no word " + word + " in " + lineId);
};
window.R05.rng = function (seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    var t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};
""")

# ---- caption groups: calm read, max 4 words, break on punctuation or a pause >= 0.15 s
words = []
for l in d["lines"]:
    for w in l["words"]:
        words.append({"t": w["w"], "s": w["s"], "e": w["e"], "line": l["id"]})
groups, cur = [], []
for i, w in enumerate(words):
    cur.append(w)
    nxt = words[i + 1] if i + 1 < len(words) else None
    punct = re.search(r"[,.?!]$", w["t"]) is not None
    pause = (nxt["s"] - w["e"]) if nxt else 9
    if len(cur) >= 4 or punct or pause >= 0.15 or nxt is None or nxt["line"] != w["line"]:
        groups.append(cur); cur = []
# merge single trailing words like "down." into previous when short and same line
merged = []
for g in groups:
    if merged and len(g) == 1 and len(merged[-1]) <= 4 and merged[-1][-1]["line"] == g[0]["line"] and not re.search(r"[.?!,]$", merged[-1][-1]["t"]):
        merged[-1] = merged[-1] + g
    else:
        merged.append(g)
groups = merged
out = []
for gi, g in enumerate(groups):
    start = max(0.1, g[0]["s"] - 0.06)
    nxt = groups[gi + 1] if gi + 1 < len(groups) else None
    end = g[-1]["e"] + 0.3
    if nxt:
        end = min(end, nxt[0]["s"] - 0.06)
    end = max(end, g[-1]["e"])
    out.append((start, end, g))

html_groups, js = [], []
for gi, (start, end, g) in enumerate(out):
    spans = []
    for wi, w in enumerate(g):
        spans.append('<span class="cw" id="cap-%d-%d"><i></i><b>%s</b></span>' % (gi, wi, w["t"]))
    html_groups.append(
        '      <div id="cap-%d" class="cap-group clip" data-start="%.3f" data-duration="%.3f" data-track-index="0">'
        '<div class="cap-pill" id="cap-%d-pill">%s</div></div>' % (gi, start, end - start, gi, " ".join(spans)))
    words_js = []
    for wi, w in enumerate(g):
        act_end = g[wi + 1]["s"] if wi + 1 < len(g) else w["e"] + 0.12
        words_js.append("[%.3f,%.3f]" % (w["s"], act_end))
    js.append("[%.3f,%.3f,[%s]]" % (start, end, ",".join(words_js)))

cap = """<!doctype html>
<html lang="en">
  <body>
    <template>
      <div id="root" data-composition-id="captions" data-duration="%(total)s">
        <style>
          #root { position: absolute; inset: 0; pointer-events: none; font-family: Inter, sans-serif; }
          .cap-group { position: absolute; left: 0; top: 1392px; width: 1080px; text-align: center; overflow: visible; }
          .cap-pill {
            display: inline-block; max-width: 900px; padding: 14px 26px 16px; border-radius: 22px;
            background: rgba(7, 22, 41, 0.78); border: 1.5px solid rgba(234, 242, 255, 0.14);
            box-shadow: 0 18px 40px rgba(0, 0, 0, 0.35);
            font-size: 54px; font-weight: 700; line-height: 1.22; letter-spacing: -0.01em; color: #eaf2ff;
          }
          .cw { position: relative; display: inline-block; padding: 0 6px; margin: 0 -2px; }
          .cw i { position: absolute; left: 0; right: 0; top: 6%%; bottom: 2%%; border-radius: 12px; background: #ff8a3d; transform-origin: 0 50%%; transform: scaleX(0); }
          .cw b { position: relative; font-weight: 700; color: rgba(234, 242, 255, 0.66); }
        </style>
%(groups)s
        <script>
          (function () {
            var G = [%(js)s];
            var tl = gsap.timeline({ paused: true });
            G.forEach(function (g, gi) {
              var pill = "#cap-" + gi + "-pill";
              tl.fromTo(pill, { opacity: 0, y: 14, filter: "blur(6px)" }, { opacity: 1, y: 0, filter: "blur(0px)", duration: 0.16, ease: "power3.out" }, g[0]);
              tl.to(pill, { opacity: 0, duration: 0.1, ease: "power2.in" }, g[1] - 0.1);
              g[2].forEach(function (w, wi) {
                var hi = "#cap-" + gi + "-" + wi + " i", tx = "#cap-" + gi + "-" + wi + " b";
                tl.fromTo(hi, { scaleX: 0, opacity: 1 }, { scaleX: 1, duration: 0.09, ease: "power2.out" }, w[0] - 0.03);
                tl.fromTo(tx, { color: "rgba(234,242,255,0.66)" }, { color: "#0b2340", duration: 0.06, ease: "none" }, w[0] - 0.03);
                tl.to(hi, { opacity: 0, duration: 0.08, ease: "none" }, w[1] - 0.03);
                tl.to(tx, { color: "#eaf2ff", duration: 0.08, ease: "none" }, w[1] - 0.03);
              });
            });
            window.__timelines["captions"] = tl;
          })();
        </script>
      </div>
    </template>
  </body>
</html>
""" % {"total": d["total"], "groups": "\n".join(html_groups), "js": ",".join(js)}
os.makedirs("compositions", exist_ok=True)
open("compositions/captions.html", "w").write(cap)
for s, e, g in out:
    print("%.2f-%.2f %s" % (s, e, " ".join(w["t"] for w in g)))
