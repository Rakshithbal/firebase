#!/usr/bin/env python3
"""Generate assets/timing.js and compositions/captions.html from the source timing.json.
Run from the project root: python3 tools/gen.py"""
import json, re, os
SRC = "/home/user/firebase/bnb-videos/r05-curing/timing.json"
d = json.load(open(SRC))
os.makedirs("assets", exist_ok=True)
lines = [{"id": l["id"], "start": l["start"], "end": l["end"],
          "words": [[w["w"], round(w["s"], 3), round(w["e"], 3)] for w in l["words"]]} for l in d["lines"]]
with open("assets/timing.js", "w") as f:
    f.write("/* Generated by tools/gen.py from r05-curing/timing.json. Do not edit by hand. */\n")
    f.write("window.R05 = { total: %s, lines: %s };\n" % (d["total"], json.dumps(lines)))
    f.write("""window.R05.at = function (lineId, word, n) {
  n = n || 1;
  var key = String(word).toLowerCase().replace(/[^a-z']/g, "");
  var line = window.R05.lines.filter(function (l) { return l.id === lineId; })[0];
  var seen = 0;
  for (var i = 0; i < line.words.length; i++) {
    if (line.words[i][0].toLowerCase().replace(/[^a-z']/g, "") === key && ++seen === n) return line.words[i][1];
  }
  throw new Error("R05.at: no word " + word + " in " + lineId);
};
window.R05.rng = function (seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    var t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};
""")

# ---- caption groups (v2 editorial): sentence-level lines.
# Break at sentence end [.?!]; at a comma once the group has >= 4 words; hard max 13 words; never across voice lines.
words = []
for l in d["lines"]:
    for w in l["words"]:
        words.append({"t": w["w"], "s": w["s"], "e": w["e"], "line": l["id"]})
groups, cur = [], []
for i, w in enumerate(words):
    cur.append(w)
    nxt = words[i + 1] if i + 1 < len(words) else None
    end_sent = re.search(r"[.?!]$", w["t"]) is not None
    comma = w["t"].endswith(",") and len(cur) >= 4
    if end_sent or comma or len(cur) >= 13 or nxt is None or nxt["line"] != w["line"]:
        groups.append(cur); cur = []
out = []
for gi, g in enumerate(groups):
    start = max(0.12, g[0]["s"] - 0.08)
    nxt = groups[gi + 1] if gi + 1 < len(groups) else None
    end = g[-1]["e"] + 0.6
    if nxt:
        end = min(end, nxt[0]["s"] - 0.08)  # hand-off: next line opens exactly as this one closes
    end = min(end, d["total"])
    out.append((start, end, g))

html_groups, js = [], []
for gi, (start, end, g) in enumerate(out):
    spans = " ".join('<span class="cw" id="cap-%d-%d">%s</span>' % (gi, wi, w["t"]) for wi, w in enumerate(g))
    html_groups.append(
        '        <div id="cap-%d" class="cap clip" data-start="%.3f" data-duration="%.3f" data-track-index="0">'
        '<p class="cap-line" id="cap-%d-line">%s</p></div>' % (gi, start, end - start, gi, spans))
    js.append("[%.3f,%.3f,[%s]]" % (start, end, ",".join("%.3f" % w["s"] for w in g)))

cap = """<!doctype html>
<html lang="en">
  <body>
    <template>
      <!-- GENERATED by tools/gen.py — edit the generator, not this file. Style: DESIGN.md §7 -->
      <div id="root" data-composition-id="captions" data-duration="%(total)s">
        <style>
          #root { position: absolute; inset: 0; pointer-events: none; }
          .cap { position: absolute; left: 0; top: 1396px; width: 1080px; height: 150px; overflow: visible; }
          .cap-line {
            margin: 0 auto; width: 880px; text-align: center;
            font-family: "InterVar", Inter, sans-serif; font-weight: 500; font-size: 44px; line-height: 56px;
            letter-spacing: -0.012em; color: #7d93ae; text-wrap: balance;
            text-shadow: 0 2px 18px rgba(6, 22, 42, 0.9);
          }
          .cw { display: inline-block; position: relative; }
        </style>
%(groups)s
        <script>
          (function () {
            // [groupStart, groupEnd, [wordStart...]] in film seconds
            var G = [%(js)s];
            var tl = gsap.timeline({ paused: true });
            G.forEach(function (g, gi) {
              var line = "#cap-" + gi + "-line";
              tl.fromTo(line, { opacity: 0, filter: "blur(5px)" }, { opacity: 1, filter: "blur(0px)", duration: 0.22, ease: "power3.out" }, g[0]);
              tl.to(line, { opacity: 0, filter: "blur(4px)", duration: 0.12, ease: "power2.in" }, g[1] - 0.12);
              g[2].forEach(function (ws, wi) {
                // spoken words settle to chalk; unspoken stay blueprint-muted
                tl.fromTo("#cap-" + gi + "-" + wi, { color: "#7d93ae" }, { color: "#eef3fa", duration: 0.14, ease: "power2.out" }, ws);
              });
            });
            window.__timelines["captions"] = tl;
          })();
        </script>
      </div>
    </template>
  </body>
</html>
""" % {"total": d["total"], "groups": "\n".join(html_groups), "js": ",".join(js)}
open("compositions/captions.html", "w").write(cap)
for s_, e_, g in out:
    print("%.2f-%.2f %s" % (s_, e_, " ".join(w["t"] for w in g)))
